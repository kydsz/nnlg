-- 014：教师导入按工号去重并发兜底（user.user_no 唯一索引）
-- ------------------------------------------------------------
-- 背景：教务教师导入（jwxt.SyncTeachers）与手工新增用户都以「先按工号查询、再插入」
--       判断是否存在，非原子。并发导入（多实例/重复点击同步）可同时通过检查，
--       插入两条同工号账号，造成同一教师两个账号（权限错乱、评教归属分裂）。
-- 方案：应用侧预检查保留（已存在则跳过、不覆盖本地配置），
--       本唯一索引作为并发兜底：败方插入命中唯一冲突（1062），
--       导入逻辑将其按「已存在 → 跳过」处理，而不是计入错误。
-- 幂等：重复执行报 Duplicate key 由 Migrate 跳过。
-- 注意：若历史库已存在重复工号（本缺陷的历史产物），加索引时唯一性校验会失败
--       （Duplicate entry）导致启动报错，需先人工合并重复账号再启动。
-- ============================================================

ALTER TABLE `user`
  ADD UNIQUE KEY `uk_user_no` (`user_no`);
